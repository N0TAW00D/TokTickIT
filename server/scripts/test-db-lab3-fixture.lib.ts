import fs from "node:fs/promises";
import path from "node:path";
import { Client } from "pg";
import {
  parseDatabaseIdentity,
  resolveTestDatabaseUrl,
  runPackageBin,
  serverRoot,
} from "./test-db.lib.js";

// Provisions a throwaway database holding *only* Lab 3-shaped schema and
// data — every migration that predates the Lab 4 one — so
// server/tests/lab-04/migration.test.ts can apply the Lab 4 migration to it
// and assert nothing in the Lab 3 tables changes (docs/lab-04/specification.md
// §7.4, tests.md §1.2 and MIG-01..MIG-05, MIG-09).
//
// Same approach and safety properties as test-db-lab2-fixture.lib.ts: a
// sibling database of the test database (name always contains "test",
// resolveTestDatabaseUrl refuses the dev database), dropped and recreated on
// every call, migrated through a throwaway Prisma config that exposes only
// the pre-Lab-4 migration folders, then hand-seeded with raw SQL.

export const LAB4_MIGRATION_SUFFIX = "_lab_04_actions_taken";

const FIXTURE_SUFFIX = "_lab3fixture";

/** Sibling of the test database: same host/port/credentials, fixed suffix. */
export function deriveLab3FixtureUrl(testDatabaseUrl: string): string {
  const identity = parseDatabaseIdentity(testDatabaseUrl);
  const fixtureUrl = new URL(testDatabaseUrl);
  fixtureUrl.pathname = `/${identity.database}${FIXTURE_SUFFIX}`;
  return fixtureUrl.toString();
}

/** Drops (if present) and recreates a database. Refuses any name that does
 * not contain "test". */
export async function recreateDatabase(databaseUrl: string): Promise<void> {
  const dbName = parseDatabaseIdentity(databaseUrl).database;
  if (!dbName.toLowerCase().includes("test")) {
    throw new Error(`Refusing to drop database "${dbName}": name does not contain "test".`);
  }

  const adminUrl = new URL(databaseUrl);
  adminUrl.pathname = "/postgres";

  const admin = new Client({ connectionString: adminUrl.toString() });
  await admin.connect();
  try {
    await admin.query(`DROP DATABASE IF EXISTS "${dbName}" WITH (FORCE)`);
    await admin.query(`CREATE DATABASE "${dbName}"`);
  } finally {
    await admin.end();
  }
}

/** Applies every migration except the Lab 4 one to `fixtureUrl`. */
async function applyPreLab4Migrations(fixtureUrl: string): Promise<void> {
  const migrationsDir = path.join(serverRoot, "prisma/migrations");
  const names = (await fs.readdir(migrationsDir, { withFileTypes: true }))
    .filter((e) => e.isDirectory() && !e.name.endsWith(LAB4_MIGRATION_SUFFIX))
    .map((e) => e.name)
    .sort();

  const tmpRoot = path.join(serverRoot, "scripts", ".lab3-fixture-tmp");
  await fs.rm(tmpRoot, { recursive: true, force: true });
  const tmpMigrations = path.join(tmpRoot, "migrations");
  await fs.mkdir(tmpMigrations, { recursive: true });

  await fs.copyFile(
    path.join(migrationsDir, "migration_lock.toml"),
    path.join(tmpMigrations, "migration_lock.toml")
  );
  for (const name of names) {
    const dest = path.join(tmpMigrations, name);
    await fs.mkdir(dest, { recursive: true });
    await fs.copyFile(path.join(migrationsDir, name, "migration.sql"), path.join(dest, "migration.sql"));
  }

  const configPath = path.join(tmpRoot, "prisma.config.ts");
  await fs.writeFile(
    configPath,
    [
      'import { defineConfig } from "prisma/config";',
      "",
      "// Generated by scripts/test-db-lab3-fixture.lib.ts — safe to delete.",
      "export default defineConfig({",
      `  schema: ${JSON.stringify(path.join(serverRoot, "prisma/schema.prisma"))},`,
      `  migrations: { path: ${JSON.stringify(tmpMigrations)} },`,
      '  datasource: { url: process.env["DATABASE_URL"] },',
      "});",
      "",
    ].join("\n"),
    "utf-8"
  );

  try {
    runPackageBin("prisma", ["migrate", "deploy", "--config", configPath], {
      cwd: serverRoot,
      env: { ...process.env, DATABASE_URL: fixtureUrl },
      stdio: "pipe",
    });
  } finally {
    await fs.rm(tmpRoot, { recursive: true, force: true });
  }
}

/** Hand-seeds Lab 3-shaped rows via raw SQL: all three roles, Tickets in
 * several statuses (including RESOLVED and an owned IN_PROGRESS one),
 * an Attachment, Public Comments and Internal Notes. */
async function seedLab3Data(fixtureUrl: string): Promise<void> {
  const client = new Client({ connectionString: fixtureUrl });
  await client.connect();
  try {
    const categories = await client.query<{ id: number }>(
      `INSERT INTO "Category" (name, "isActive") VALUES ('Hardware', true), ('Software', true) RETURNING id`
    );
    const systems = await client.query<{ id: number }>(
      `INSERT INTO "RelatedSystem" (name, "isActive") VALUES ('Printer', true), ('Email', true) RETURNING id`
    );
    const [cat1, cat2] = categories.rows.map((r) => r.id);
    const [sys1, sys2] = systems.rows.map((r) => r.id);

    // passwordHash is a placeholder string: nothing here logs in.
    const users = await client.query<{ id: number }>(
      `INSERT INTO "User" (name, email, "passwordHash", role, "isActive", "mustChangePassword", "updatedAt")
       VALUES
         ('Lab3 Requester', 'lab3.requester@example.edu', 'not-a-real-hash', 'REQUESTER', true, false, now()),
         ('Lab3 Second Requester', 'lab3.requester2@example.edu', 'not-a-real-hash', 'REQUESTER', true, false, now()),
         ('Lab3 Staff', 'lab3.staff@example.edu', 'not-a-real-hash', 'IT_STAFF', true, false, now()),
         ('Lab3 Admin', 'lab3.admin@example.edu', 'not-a-real-hash', 'ADMINISTRATOR', true, false, now())
       RETURNING id`
    );
    const [requesterId, requester2Id, staffId] = users.rows.map((r) => r.id);

    const tickets = await client.query<{ id: number }>(
      `INSERT INTO "Ticket"
         ("ticketNumber", "requesterId", "categoryId", "relatedSystemId", summary, description,
          "requestedPriority", "itPriority", status, "ownerId", "updatedAt")
       VALUES
         ('TKT-LAB3-000001', $1, $4, $6, 'Lab 3 fixture new ticket', 'Fixture description, at least twenty characters.', 'MEDIUM', 'MEDIUM', 'NEW', NULL, now()),
         ('TKT-LAB3-000002', $2, $5, $7, 'Lab 3 fixture in-progress ticket', 'Fixture description, at least twenty characters.', 'HIGH', 'HIGH', 'IN_PROGRESS', $3, now()),
         ('TKT-LAB3-000003', $1, $5, $7, 'Lab 3 fixture resolved ticket', 'Fixture description, at least twenty characters.', 'LOW', 'LOW', 'RESOLVED', $3, now()),
         ('TKT-LAB3-000004', $2, $4, $6, 'Lab 3 fixture closed ticket', 'Fixture description, at least twenty characters.', 'LOW', 'LOW', 'CLOSED', $3, now())
       RETURNING id`,
      [requesterId, requester2Id, staffId, cat1, cat2, sys1, sys2]
    );
    const [t1, t2, t3] = tickets.rows.map((r) => r.id);

    await client.query(
      `INSERT INTO "Attachment"
         ("ticketId", "originalFilename", "storedFilename", "mimeType", "fileSize")
       VALUES ($1, 'notes.txt', 'lab3-fixture-notes.txt', 'text/plain', 128)`,
      [t1]
    );
    await client.query(
      `INSERT INTO "PublicComment" ("ticketId", "authorId", body)
       VALUES ($1, $3, 'Public comment from the requester.'), ($2, $4, 'Public comment from staff.')`,
      [t1, t2, requesterId, staffId]
    );
    await client.query(
      `INSERT INTO "InternalNote" ("ticketId", "authorId", body)
       VALUES ($1, $2, 'Internal note on the resolved ticket.')`,
      [t3, staffId]
    );
  } finally {
    await client.end();
  }
}

/**
 * Drops and recreates the Lab 3-shaped fixture database, applies every
 * pre-Lab-4 migration and seeds Lab 3-shaped rows. Returns its URL.
 */
export async function resetLab3FixtureDatabase(): Promise<string> {
  const fixtureUrl = deriveLab3FixtureUrl(resolveTestDatabaseUrl());

  await recreateDatabase(fixtureUrl);
  await applyPreLab4Migrations(fixtureUrl);
  await seedLab3Data(fixtureUrl);

  return fixtureUrl;
}
